function normalizeHandlingId(id) {
  return String(id || '').trim().toUpperCase();
}

function isVanillaHandlingId(id) {
  const key = normalizeHandlingId(id);
  return key.length > 0 && VANILLA_HANDLING_IDS.has(key);
}

