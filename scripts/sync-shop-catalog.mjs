#!/usr/bin/env node
'use strict';

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const catalogPath = path.join(root, 'resources/[sunset]/sunset_shop/shared/catalog.json');
const outPath = path.join(root, 'panel/src/generated/shop-catalog.ts');

const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));

function extractShopLocale(luaPath) {
  const src = fs.readFileSync(luaPath, 'utf8');
  const map = {};
  for (const m of src.matchAll(/\["(shop\.[^"]+)"\]\s*=\s*"((?:\\.|[^"\\])*)"/g)) {
    map[m[1]] = m[2].replace(/\\"/g, '"');
  }
  for (const m of src.matchAll(/\["(clans\.err\.clan_is_expired)"\]\s*=\s*"((?:\\.|[^"\\])*)"/g)) {
    map[m[1]] = m[2].replace(/\\"/g, '"');
  }
  return map;
}

const gameEn = extractShopLocale(path.join(root, 'resources/[sunset]/sunset_core/shared/locales/en.lua'));
const gameRo = extractShopLocale(path.join(root, 'resources/[sunset]/sunset_core/shared/locales/ro.lua'));
const localeOutPath = path.join(root, 'panel/src/generated/shop-game-locales.ts');

const banner = `/* eslint-disable */
// AUTO-GENERATED by scripts/sync-shop-catalog.mjs — do not edit manually.
// Source: resources/[sunset]/sunset_shop/shared/catalog.json
`;

const body = `${banner}
export type ShopCatalogProduct = {
  id: string;
  category: string;
  labelKey: string;
  descriptionKey: string;
  currency: 'rc';
  price: number;
  enabled: boolean;
  repeatable?: boolean;
  cooldown?: number;
  entitlement?: string;
  icon?: string;
  handler?: string;
  input?: 'tag' | 'color';
  requiresLeader?: boolean;
  clanAction?: string;
  slots?: number;
  days?: number;
  bankAmount?: number;
};

export type ShopCatalogCategory = {
  id: string;
  labelKey: string;
  icon: string;
  order: number;
};

export const shopConfig = ${JSON.stringify(catalog.config, null, 2)} as const;

export const shopCategories: ShopCatalogCategory[] = ${JSON.stringify(catalog.categories, null, 2)};

export const shopProducts: Record<string, ShopCatalogProduct> = ${JSON.stringify(catalog.products, null, 2)};

export function listEnabledShopProducts(): ShopCatalogProduct[] {
  return Object.values(shopProducts)
    .filter((p) => p.enabled === true)
    .sort((a, b) => {
      const ca = shopCategories.find((c) => c.id === a.category)?.order ?? 99;
      const cb = shopCategories.find((c) => c.id === b.category)?.order ?? 99;
      if (ca !== cb) return ca - cb;
      if (a.price !== b.price) return a.price - b.price;
      return a.id.localeCompare(b.id);
    });
}
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, body, 'utf8');
console.log('Wrote', path.relative(root, outPath));

const localeBody = `${banner}
export const shopGameLocalesEn: Record<string, string> = ${JSON.stringify(gameEn, null, 2)};

export const shopGameLocalesRo: Record<string, string> = ${JSON.stringify(gameRo, null, 2)};

export function shopGameT(locale: 'en' | 'ro', key: string): string {
  const dict = locale === 'ro' ? shopGameLocalesRo : shopGameLocalesEn;
  return dict[key] || shopGameLocalesEn[key] || key;
}
`;
fs.writeFileSync(localeOutPath, localeBody, 'utf8');
console.log('Wrote', path.relative(root, localeOutPath));
