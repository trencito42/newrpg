    const generated = window.SunsetGeneratedLocales || {};
    Object.assign(dictionaries.en, generated.en || {});
    Object.assign(dictionaries.ro, generated.ro || {});

    let locale = 'en';
    const warned = new Set();
    const valid = (value) => Object.prototype.hasOwnProperty.call(dictionaries, value);
    const interpolate = (text, params) => String(text).replace(/\{([a-zA-Z0-9_]+)\}/g, (all, key) =>
        Object.prototype.hasOwnProperty.call(params || {}, key) ? String(params[key]) : all);

    function t(key, params) {
        const primary = dictionaries[locale][key];
        if (window.SUNSET_I18N_STRICT) {
            const context = `[I18n] locale=${locale} key=${key}`;
            if (typeof primary !== 'string' || !primary.trim()) throw new Error(`${context}: missing translation`);
            for (const match of primary.matchAll(/\{([a-zA-Z0-9_]+)\}/g)) {
                if (params?.[match[1]] === undefined) throw new Error(`${context}: missing parameter {${match[1]}}`);
            }
        }
        const value = primary ?? dictionaries.en[key];
        if (value === undefined) {
            if (!warned.has(key)) { warned.add(key); console.warn(`[I18n] Missing key: ${key}`); }
            // Players never see a raw key: debug builds keep the [?key] marker,
            // production shows a readable phrase from the last key segment.
            if (window.SUNSET_I18N_DEBUG) return `[?${key}]`;
            const last = String(key).split('.').pop().replace(/_/g, ' ');
            return last.charAt(0).toUpperCase() + last.slice(1);
        }
        return interpolate(value, params);
    }

    function translateTree(root = document) {
        root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
        root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
        root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
        root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
        root.querySelectorAll('[data-i18n-alt]').forEach((el) => { el.alt = t(el.dataset.i18nAlt); });
        root.querySelectorAll('[data-i18n-value]').forEach((el) => { el.value = t(el.dataset.i18nValue); });
    }

    function setLocale(next) {
        next = String(next || '').toLowerCase();
        if (!valid(next)) return false;
        locale = next;
        try { window.localStorage.setItem('sunset_locale', next); } catch (_) { /* unavailable in restricted CEF */ }
        document.documentElement.lang = next;
        translateTree(document);
        window.dispatchEvent(new CustomEvent('sunset:localeChanged', { detail: { locale: next } }));
        return true;
    }

    const numberLocale = () => locale === 'ro' ? 'ro-RO' : 'en-US';
    window.I18n = Object.freeze({
        t, setLocale, translateTree, getLocale: () => locale,
        hasLocale: valid,
        // Staff-authored data labels (route/place names from JSON/config): Romanian looks up label.<slug>, English keeps the data value.
        label: (text) => {
            const raw = String(text ?? '');
            if (locale === 'en') return raw;
            const key = 'label.' + raw.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
            return dictionaries[locale][key] || raw;
        },
        intlLocale: numberLocale,
        // Locale-aware date/time helpers (account language, not the CEF default).
        date: (value, options) => new Date(value).toLocaleDateString(numberLocale(), options),
        time: (value, options) => new Date(value).toLocaleTimeString(numberLocale(), options),
        number: (value, options) => new Intl.NumberFormat(numberLocale(), options).format(Number(value) || 0),
        money: (value) => '$' + new Intl.NumberFormat(numberLocale(), { maximumFractionDigits: 0 }).format(Number(value) || 0),
        distance: (metres) => Number(metres) >= 1000
            ? `${new Intl.NumberFormat(numberLocale(), { maximumFractionDigits: 1 }).format(Number(metres) / 1000)} km`
            : `${new Intl.NumberFormat(numberLocale(), { maximumFractionDigits: 0 }).format(Number(metres) || 0)} m`,
        // Item display names: Romanian uses the item.<id> catalogue; English keeps the server label (staff-editable).
        item: (id, fallback) => (locale === 'en' ? (fallback || dictionaries.en[`item.${id}`] || id) : (dictionaries[locale][`item.${id}`] || fallback || id)),
        plural: (baseKey, count, params) => t(`${baseKey}.${Number(count) === 1 ? 'one' : 'other'}`, { ...(params || {}), count }),
        dictionaries,
    });

    window.addEventListener('message', (event) => {
        const message = event.data || {};
        if (message.action !== 'localeSet') return;
        const payload = message.data || message.payload || {};
        if (typeof payload.strict === 'boolean') window.SUNSET_I18N_STRICT = payload.strict;
        setLocale(payload.locale || message.locale);
    });

    try {
        const savedLocale = window.localStorage.getItem('sunset_locale');
        if (valid(savedLocale)) locale = savedLocale;
    } catch (_) { /* use English default */ }
    document.addEventListener('DOMContentLoaded', () => {
        document.documentElement.lang = locale;
        translateTree(document);
    }, { once: true });
